# Agreement between two colourings under each of the 6 relabellings of the colours, read from their 3x3 count table.
PERMUTATIONS = [(0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]


def evaluate(solution: dict) -> float:
    colourings = solution["colourings"]
    if not isinstance(colourings, list) or not 1 <= len(colourings) <= MAX_COLOURINGS:
        raise ValueError(f"Expected between 1 and {MAX_COLOURINGS} colourings")
    for c in colourings:
        if not isinstance(c, str) or len(c) != VERTICES or set(c) - {"0", "1", "2"}:
            raise ValueError(f"Every colouring must be a string of {VERTICES} characters '0', '1' or '2'")

    colours = np.frombuffer("".join(colourings).encode(), dtype=np.uint8).reshape(len(colourings), VERTICES) - ord("0")
    edges = np.array(EDGES)
    conflicts = (colours[:, edges[:, 0]] == colours[:, edges[:, 1]]).sum(axis=1)
    good = colours[conflicts <= MAX_CONFLICTS]

    # Walk the good colourings in order and keep each one that differs from every kept colouring on at least
    # MIN_DIFFERENCE vertices, under the best relabelling of the colours.
    kept = np.zeros((len(good), 3, VERTICES), dtype=np.float64)
    count = 0
    for c in good:
        one_hot = (c[:, None] == np.arange(3)).astype(np.float64)
        if count:
            # Sums of 0/1 entries are exact in float64; some BLAS builds raise spurious floating-point warnings here.
            with np.errstate(all="ignore"):
                table = (kept[:count].reshape(count * 3, VERTICES) @ one_hot).reshape(count, 3, 3)
            agreement = np.max([table[:, 0, p[0]] + table[:, 1, p[1]] + table[:, 2, p[2]] for p in PERMUTATIONS], axis=0)
            if VERTICES - agreement.max() < MIN_DIFFERENCE:
                continue
        kept[count] = one_hot.T
        count += 1
    return float(count)
